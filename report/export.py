def _summary_de(t: dict) -> str:
    """German version of liquidity_trend()["summary"], built from the same fields (no new numbers)."""
    if t["verdict"] is None:
        return TREND_HELP_DE[None]

    def word(c, lower_is_better):
        if abs(c) < LIQUIDITY_TREND_TOL:
            return "etwa gleich"
        return "besser" if (c < 0) == lower_is_better else "schlechter"

    sp = formatters("de")["spct0"]
    parts = []
    if t["xlm_25k_change_pct"] is not None:
        parts.append(f"Handelskosten {sp(t['xlm_25k_change_pct'])} ({word(t['xlm_25k_change_pct'], True)})")
    if t["turnover_change_pct"] is not None:
        parts.append(f"Umsatz {sp(t['turnover_change_pct'])} ({word(t['turnover_change_pct'], False)})")
    w = t["window"]
    out = f"{VERDICT['de'][t['verdict']]}: " + ", ".join(parts) + f", letzte {w} vs. vorherige {w} Handelstage."
    ip = [f"{lbl} {sp(t[key])}" for key, lbl in (("index_xlm_25k_change_pct", "Handelskosten"),
                                                         ("index_turnover_change_pct", "Umsatz")) if t[key] is not None]
    if ip:
        out += f" {t['index']}-Median: " + ", ".join(ip) + "."
    ds = t["ds_category"] or {}
    if ds.get("now") and ds.get("before") and ds["now"] != ds["before"]:
        out += f" Designated-Sponsor-Kategorie (Schätzung): {ds['before']} -> {ds['now']}."
    return out


def _size_label(label: str | None, lang: str) -> str:
    """Order-size label from engine.xlm ('€2.5m', '€100k') in the report style: EN '€2.5m', DE '2,5 Mio. EUR'."""
    if not label:
        return "n/a"
    if lang != "de":
        return label
    v = label.lstrip("€")
    unit = " Mio. EUR" if v.endswith("m") else " Tsd. EUR"
    return v[:-1].replace(".", ",") + unit


def part_a_data(isin: str, peer_by: str = "index") -> dict:
    """Collect the engine output the Part A report shows. Selects and joins; computes no new numbers."""
    from engine import baseline, data, xlm

    s = data.stock(isin)
    curve = xlm.cost_curve(isin, peer_by)
    cs = xlm.curve_summary(curve)
    peer_ok = curve[curve["peer_bps"].notna()]
    cs["peer_largest_absorbed_label"] = peer_ok["label"].iloc[-1] if len(peer_ok) else None

    eps = baseline.anomaly_episodes(isin)
    ev = data.events()
    ev = ev[ev["isin"] == isin]
    ev_day = pd.to_datetime(ev["reaction_day"])
    top = eps.sort_values("severity", ascending=False).head(MAX_EPISODES).sort_values("start", ascending=False)
    top = top.assign(max_vol_ratio=baseline.episode_card_ratio(isin, top))
    episodes = [{"start": pd.Timestamp(r.start).date().isoformat(), "end": pd.Timestamp(r.end).date().isoformat(),
                 "days": int(r.days),
                 "event": " · ".join(ev.loc[(ev_day >= r.start) & (ev_day <= r.end), "title"]),
                 "context": [f for f in str(r.context or "").split(", ") if f],
                 "reason": [x for x in str(r.reason).split(", ") if x],
                 "peak_abn_ret": r.peak_abn_ret, "total_abn_ret": r.total_abn_ret, "max_vol_ratio": r.max_vol_ratio}
                for r in top.itertuples()]
    return {"isin": isin, "name": data.display_name(isin), "kpis": baseline.kpis(isin),
            "trend": baseline.liquidity_trend(isin), "curve": cs, "peer_by": peer_by,
            "episodes": episodes, "n_episodes": len(eps),
            "period": {"start": s["date"].min().date().isoformat(), "end": s["date"].max().date().isoformat(),
                       "days": len(s)}}


def part_a_html(isin: str, lang: str = "en", peer_by: str = "index") -> str:
    """Part A IR report (DE/EN) for one stock. peer_by = 'index' | 'sector' | 'size' (dashboard 'Compare with')."""
    lang = lang if lang in LABELS_A else "en"
    d = part_a_data(isin, peer_by)
    k, t = d["kpis"], d["trend"]

    def peer_label(by):
        g = k["peer_groups"][by]
        if g["fallback"]:  # sector unknown -> the engine uses the index group
            return PEER_LABEL[lang]["index"].format(g["name"])
        name = _size_de(g["name"]) if (by == "size" and lang == "de") else g["name"]
        return PEER_LABEL[lang][by].format(name)

    used_ctx = list(dict.fromkeys(f for e in d["episodes"] for f in e["context"]))
    ctx_help = CONTEXT_HELP_DE if lang == "de" else CONTEXT_HELP
    return ENV.get_template("template_part_a.html").render(
        d=d, k=k, t=t, cs=d["curve"], lang=lang, L=LABELS_A[lang], peer_label=peer_label,
        verdict=VERDICT[lang].get(t["verdict"]), vs_word=VS_WORD[lang],
        summary=t["summary"] if lang == "en" else _summary_de(t),
        trend_help=t["help"] if lang == "en" else TREND_HELP_DE[t["verdict"]],
        ctx_words=CONTEXT_WORDS[lang], ctx_help=[(CONTEXT_WORDS[lang].get(f, f), ctx_help.get(f, "")) for f in used_ctx],
        reason_word=(lambda r: REASON_DE.get(r, r)) if lang == "de" else (lambda r: r),
        size_word=_size_de if lang == "de" else (lambda n: n),
        label_eur=lambda s: _size_label(s, lang), **_fmt(lang))
