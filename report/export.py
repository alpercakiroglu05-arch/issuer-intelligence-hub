from io import BytesIO
from pathlib import Path

from jinja2 import Environment, FileSystemLoader

ENV = Environment(loader=FileSystemLoader(Path(__file__).parent), autoescape=True)

LABELS = {
    "en": dict(title="Event impact", day="reaction day", abn="Stock-specific move", stock="stock", peers="peers",
               vol="Turnover vs normal", xlm="Trading cost (XLM 25k)", normal="normal", agent="Agent order imbalance",
               auction="auction share",
               foot="Source: Deutsche Boerse Xetra data (OHLC, Flow Dynamics, XLM). Peers = equal-weighted index members. "
                    "Generated by Issuer Intelligence Hub. Not investment advice."),
    "de": dict(title="Ereignis-Auswirkung", day="Reaktionstag", abn="Unternehmensspezifische Bewegung", stock="Aktie",
               peers="Vergleichswerte", vol="Umsatz vs. normal", xlm="Handelskosten (XLM 25k)", normal="normal",
               agent="Agenten-Orderüberhang", auction="Auktionsanteil",
               foot="Quelle: Deutsche Börse Xetra-Daten (OHLC, Flow Dynamics, XLM). Vergleich = gleichgewichtete Indexmitglieder. "
                    "Erstellt mit Issuer Intelligence Hub. Keine Anlageberatung."),
}


def _fmt():
    def na(v): return v is None or v != v
    def pct(x): return "n/a" if na(x) else f"{x * 100:+.1f}%"
    def pct0(x): return "n/a" if na(x) else f"{x * 100:.0f}%"
    def x(v): return "n/a" if na(v) else f"{v:.1f}x"
    def bps(v): return "n/a" if na(v) else f"{v:.0f} bps"
    def eur(v): return "n/a" if na(v) else (f"EUR {v / 1e6:.1f}m" if v >= 1e6 else f"EUR {v / 1e3:.0f}k")
    return dict(pct=pct, pct0=pct0, x=x, bps=bps, eur=eur)


def to_html(card: dict, narrative: str, lang: str = "en") -> str:
    return ENV.get_template("template.html").render(card=card, narrative=narrative, lang=lang,
                                                    L=LABELS.get(lang, LABELS["en"]), **_fmt())


def to_pdf(html: str) -> bytes | None:
    try:
        from xhtml2pdf import pisa
    except ImportError:
        return None
    buf = BytesIO()
    pisa.CreatePDF(html, dest=buf, encoding="utf-8")
    return buf.getvalue()
